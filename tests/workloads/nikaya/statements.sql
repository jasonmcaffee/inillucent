-- from migrations/inillucent/002_queue_indexes.sql
-- Plain indexes for the two work queues, because a partial index is never chosen.
--
-- `001_init.sql` carries the two partial indexes PostgreSQL had:
--
--   CREATE INDEX document_pending_index_idx ON document (indexed_at)
--     WHERE indexed_at IS NULL AND deleted_at IS NULL;
--   CREATE INDEX attachment_download_queue_pending_idx ON attachment_download_queue (status)
--     WHERE status = 'queued';
--
-- Both are accepted and stored, and neither is ever selected - not even for a query whose predicate
-- is character for character the index's own `WHERE` clause. Reproduced on three rows: a table with a
-- partial index on `(done) WHERE done IS NULL AND gone IS NULL` plans `SELECT id FROM t WHERE done IS
-- NULL AND gone IS NULL` as a full `SCAN`, and adding a plain index on the same column turns it into
-- a covering index scan. Filed as part of task-1880.
--
-- The cost here was not small. `document` is 66,776 rows whose leaves carry the message body and the
-- raw provider payload, so the scan the ingestion pass runs to find its own backlog read gigabytes of
-- text to answer a question that normally has no rows at all: measured at **1,280 ms**, on a queue
-- that is usually empty.
--
-- These are the plain indexes the planner does use. The partial ones are left in place: they cost
-- little, they are correct, and they are what should be selected once the planner can.

CREATE INDEX IF NOT EXISTS document_indexed_at_idx ON document (indexed_at);
CREATE INDEX IF NOT EXISTS attachment_download_queue_status_idx ON attachment_download_queue (status);

-- from migrations/inillucent/003_embedded_flag.sql
-- A flag on the chunk, because a LEFT JOIN is a nested loop with the inner side scanned.
--
-- "Which chunks have no vector yet" was an anti join: `chunk LEFT JOIN chunk_embedding ON
-- e.chunk_id = c.id AND e.embedding_model = ? WHERE e.chunk_id IS NULL`. PostgreSQL answered it with
-- a hash anti join in milliseconds. Here the plan is
--
--   SCAN c USING COVERING INDEX sqlite_autoindex_chunk_1
--   SCAN e
--
-- - the outer side scanned, and the inner side scanned again for every one of its rows. On this
-- corpus that is 601,862 x 601,862, and it does not finish: a sync sat on one core for nine minutes
-- with no disk and no network before it was stopped, and it had not left the first phase.
--
-- The same join written as `NOT EXISTS` is no better, and an INNER JOIN on the identical key **is**
-- planned as an index seek, so this is specific to the outer join rather than to the key. Filed as
-- part of task-1880.
--
-- So the question stops being a join. `chunk.embedded_at` records when a chunk's vector was written,
-- `store_embeddings` sets it in the same transaction as the vector, and the queue query becomes a
-- seek on an index. The two counts stay derivable from `chunk_embedding`, so nothing here is the only
-- copy of anything: this column is a cache of a fact the other table already holds, and the
-- reconciliation that repairs the retrieval index would show it up if it ever drifted.

ALTER TABLE chunk ADD COLUMN embedded_at INTEGER;

CREATE INDEX IF NOT EXISTS chunk_embedded_at_idx ON chunk (embedded_at);

-- `embedding_attempts >= 3` is the poison chunk check, and `001_init.sql` indexes it partially -
-- `WHERE embedding_attempts > 0` - which is never selected. A plain index is.
CREATE INDEX IF NOT EXISTS chunk_embedding_attempts_plain_idx ON chunk (embedding_attempts);

-- from migrations/inillucent/004_embedding_queue.sql
-- The embedding backlog as a table, because neither of the other two ways works here.
--
-- The question is "which chunks have no vector yet", asked once per ingestion page and once per
-- status render. Three ways to answer it, and the first two are closed:
--
-- 1. **Anti join** - `chunk LEFT JOIN chunk_embedding ... WHERE e.chunk_id IS NULL`, which is what
--    PostgreSQL answered with a hash anti join in milliseconds. Here a LEFT JOIN is a nested loop
--    with the inner side scanned: `SCAN c` then `SCAN e`, which on 601,862 rows is 601,862 squared
--    and does not finish. `NOT EXISTS` is planned no better. An INNER JOIN on the identical key *is*
--    an index seek, so this is specific to the outer join.
--
-- 2. **A flag on the chunk** - `003_embedded_flag.sql` added `chunk.embedded_at` for exactly this.
--    Filling it is the problem. Per row, it is 601,862 seeks and rewrites of a row over a kilobyte
--    wide, measured at 1 MB/s and about an hour; and the run that was killed part way through left a
--    database whose redo log could not be replayed. Set based, in one statement, it fails outright:
--
--        Error: the mini-columns do not fit in one page
--
--    A column added by ALTER TABLE and then filled on every row makes some leaf need a layout it
--    cannot have. So the column is there, empty, and unused; it is left rather than dropped because
--    dropping it is another rewrite of every row. Both failures are on task-1880.
--
-- 3. **A queue**, which is this. A chunk is put here when it is written and taken out when its
--    vector is stored, both inside the transaction that does the other half, so the two can never
--    disagree. In the steady state it holds nothing, so the question costs nothing to ask.
--
-- It starts empty, and empty is the correct starting state: every one of the 601,862 chunks in this
-- corpus has a vector, which is checked rather than assumed - `chunk` and `chunk_embedding` both
-- count 601,862. A chunk that somehow has neither a vector nor a queue row would be invisible to the
-- embedding pass, so `nikaya-server reconcile-embedding-queue` re-derives the queue from the two
-- tables and is what a suspicion gets answered with.

CREATE TABLE IF NOT EXISTS embedding_queue (
  chunk_id  TEXT PRIMARY KEY REFERENCES chunk(id) ON DELETE CASCADE,
  queued_at INTEGER NOT NULL
);

