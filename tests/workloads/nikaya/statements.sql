-- Vectors are versioned by model so two embedding spaces are never mixed in one index.
--
-- The column is declared VECTOR(768) rather than BLOB so a value that is not 768 floats wide is
-- refused when it is written. A wrong width is otherwise found when the retrieval index is built,
-- which is minutes later and a long way from the code that produced it.
--
-- There is deliberately no `USING inillucent_hnsw` index over this column. That index is the same
-- HNSW the retrieval engine runs, so building one here would be a second graph over the same
-- 601,862 vectors, maintained on every write, to answer a query nothing asks: retrieval goes through
-- `services/retrieval.rs`. Leaving it unindexed also means `ORDER BY vector_distance_cos(...)` here
-- is an exhaustive scan and therefore exact, which gives the recall gate an oracle in the same file.
CREATE TABLE chunk_embedding (
  chunk_id        TEXT NOT NULL REFERENCES chunk(id) ON DELETE CASCADE,
  embedding_model TEXT NOT NULL,
  dimension       INTEGER NOT NULL,
  embedding       VECTOR(768) NOT NULL,
  indexed_at      INTEGER NOT NULL,
  PRIMARY KEY (chunk_id, embedding_model)
);

